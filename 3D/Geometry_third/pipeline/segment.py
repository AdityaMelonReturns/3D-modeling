"""Stage [E]: Defect Segmentation (SAM2), prompted per image with a box.

Confirmed on this machine (CPU): ~4s model load (once), ~28s/image (image
encoder pass) + ~0.3s per prompt. Workable on CPU for a handful of images
(a full 8-image set ~= 4 minutes), unlike Depth Pro.

Box prompts are NOT auto-generated by a detector here - per the spec
("Claude can draw/pick this"), boxes are supplied externally, one per shot,
in a small JSON file (see prompts/<defect_id>.json). In practice: view each
image, eyeball the defect's bounding box, write it down. This avoids needing
an ANTHROPIC_API_KEY just to run segmentation; Claude-vision auto-boxing can
be added later as a convenience, this keeps the pipeline runnable without it.
"""
import json
import os

import numpy as np
from sam2.build_sam import build_sam2
from sam2.sam2_image_predictor import SAM2ImagePredictor


class DefectSegmenter:
    def __init__(self, config="configs/sam2.1/sam2.1_hiera_l.yaml",
                 checkpoint="checkpoints/sam2/sam2.1_hiera_large.pt",
                 device=None):
        import torch
        device = device or ("cuda" if torch.cuda.is_available() else "cpu")
        model = build_sam2(config, checkpoint, device=device)
        self.predictor = SAM2ImagePredictor(model)
        self.device = device

    def segment(self, image_rgb, box_xyxy, dilate_pct=0.15, neg_points=None):
        """box_xyxy: (x0,y0,x1,y1) pixel box around the visible defect.
        neg_points: optional list of [x,y] pixel points to EXCLUDE from the
        mask - use this when a scale card/ruler or other object sits inside
        the box and touches the defect (SAM2 otherwise merges touching
        objects into one mask - confirmed on ceiling__shot_05, where the
        ruler got absorbed into the defect mask with box-only prompting).
        Returns dict(mask: HxW bool, mask_dilated: HxW bool, score: float)."""
        self.predictor.set_image(image_rgb)
        point_coords, point_labels = None, None
        if neg_points:
            point_coords = np.array(neg_points)
            point_labels = np.zeros(len(neg_points))  # 0 = exclude
        masks, scores, _ = self.predictor.predict(
            box=np.array(box_xyxy), point_coords=point_coords, point_labels=point_labels,
            multimask_output=False,
        )
        mask = masks[0].astype(bool)
        mask_dilated = _dilate_mask(mask, box_xyxy, dilate_pct)
        return {"mask": mask, "mask_dilated": mask_dilated, "score": float(scores[0])}


def _dilate_mask(mask, box_xyxy, pct):
    from scipy import ndimage
    x0, y0, x1, y1 = box_xyxy
    box_diag = np.hypot(x1 - x0, y1 - y0)
    iterations = max(1, int(box_diag * pct / 10))  # rough px-per-iteration heuristic
    return ndimage.binary_dilation(mask, iterations=iterations)


def load_prompts(prompts_path):
    """prompts/<defect_id>.json shape - two forms per shot, both valid:
      "ceiling__shot_05": [540, 350, 1090, 800]                        # box only
      "wood1__shot_04": {"box": [...], "neg_points": [[955, 480]]}     # box + exclusions
    Shots with no entry are simply omitted -> skipped. Returns a dict of
    {shot_name: {"box": [...], "neg_points": [...] or None}}, normalized."""
    if not os.path.exists(prompts_path):
        return {}
    with open(prompts_path) as f:
        raw = json.load(f)
    normalized = {}
    for name, v in raw.items():
        if isinstance(v, dict):
            normalized[name] = {"box": v["box"], "neg_points": v.get("neg_points")}
        else:
            normalized[name] = {"box": v, "neg_points": None}
    return normalized
